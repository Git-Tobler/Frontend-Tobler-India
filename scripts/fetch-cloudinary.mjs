// Pulls the asset list out of Cloudinary and writes src/data/media.js, so the
// public IDs the site renders are a checked-in manifest rather than a live API
// call — the browser never talks to the Admin API, and a build can't break
// because the media account is unreachable.
//
// Run after uploading or renaming assets:  npm run media
//
// Credentials come from .env (API secret stays server-side; only the cloud
// name is ever exposed to the client, via VITE_CLOUDINARY_CLOUD_NAME).
import { writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const env = Object.fromEntries(
  readFileSync(fileURLToPath(new URL('../.env', import.meta.url)), 'utf8')
    .split('\n')
    .map((line) => line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$/))
    .filter(Boolean)
    .map((m) => [m[1], m[2]])
)

const cloud = (env.VITE_CLOUDINARY_CLOUD_NAME || env.Cloudinary_CLOUD_NAME || '').trim()
const key = (env.Cloudinary_API_KEY || '').trim()
const secret = (env.Cloudinary_API_SECRET || '').trim()

if (!cloud || !key || !secret) {
  console.error('Missing VITE_CLOUDINARY_CLOUD_NAME / Cloudinary_API_KEY / Cloudinary_API_SECRET in .env')
  process.exit(1)
}

const auth = 'Basic ' + Buffer.from(`${key}:${secret}`).toString('base64')

// The Admin API pages at 500 max; follow next_cursor so a growing library
// doesn't silently truncate to the first page.
async function listAll(kind) {
  const out = []
  let cursor
  do {
    const url = new URL(`https://api.cloudinary.com/v1_1/${cloud}/resources/${kind}`)
    url.searchParams.set('max_results', '500')
    if (cursor) url.searchParams.set('next_cursor', cursor)
    const res = await fetch(url, { headers: { Authorization: auth } })
    if (!res.ok) throw new Error(`${kind}: ${res.status} ${await res.text()}`)
    const body = await res.json()
    out.push(...body.resources)
    cursor = body.next_cursor
  } while (cursor)
  return out
}

const shape = (r) => ({
  id: r.public_id,
  w: r.width,
  h: r.height,
  format: r.format,
  folder: r.folder || r.asset_folder || '',
})

const [images, videos] = await Promise.all([listAll('image'), listAll('video')])

const file = `// GENERATED by scripts/fetch-cloudinary.mjs — do not edit by hand.
// Run \`npm run media\` to refresh after uploading or renaming assets.
// \`id\` is the Cloudinary public ID; pass it to the builders in src/lib/cloudinary.js.

export const CLOUDINARY_IMAGES = ${JSON.stringify(images.map(shape), null, 2)}

export const CLOUDINARY_VIDEOS = ${JSON.stringify(videos.map(shape), null, 2)}

// Lookup by public ID, for slots that name a specific asset.
export const MEDIA_BY_ID = Object.fromEntries(
  [...CLOUDINARY_IMAGES, ...CLOUDINARY_VIDEOS].map((m) => [m.id, m])
)
`

writeFileSync(fileURLToPath(new URL('../src/data/media.js', import.meta.url)), file)
console.log(`media.js written — ${images.length} images, ${videos.length} videos`)

const folders = [...new Set([...images, ...videos].map((r) => r.folder || r.asset_folder || '(root)'))]
console.log('folders:', folders.join(', '))
